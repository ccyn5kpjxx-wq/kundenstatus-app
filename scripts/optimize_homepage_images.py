"""Build public responsive WebP assets without cropping or changing originals.

Run after replacing a public source image. Output names contain the source and
encoding-profile hash, so a changed image never reuses an old browser URL.
"""
from __future__ import annotations

import ast
import hashlib
import json
import pprint
import re
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "static"
WIDTHS = (240, 480, 800, 1200, 1600)
PROFILE = "webp-q80-logo90-method6-aspect-v1"
TEMPLATES = tuple(sorted((ROOT / "templates").glob("homepage*.html"))) + (
    ROOT / "templates/_homepage_arbeitsbilder.html",
)


def source_images() -> list[str]:
    sources = {"logo-transparent.png"}
    for template in TEMPLATES:
        sources.update(re.findall(
            r"['\"]((?:homepage|images|mietwagen)/[^'\"{}]+\.(?:png|jpe?g|webp))['\"]",
            template.read_text(encoding="utf-8"),
        ))
    # Read public service metadata, without importing the app or loading secrets.
    for node in ast.parse((ROOT / "app.py").read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "HOMEPAGE_LEISTUNGEN"
            for target in node.targets
        ):
            for service in ast.literal_eval(node.value).values():
                sources.add("homepage/" + service["bild"])
    sources.update(p.relative_to(STATIC).as_posix() for p in (STATIC / "homepage").glob("hero-*-20261021.webp"))
    return sorted(sources)


def main() -> None:
    images = {}
    for filename in source_images():
        source = STATIC / filename
        if not source.is_file():
            raise FileNotFoundError(source)
        digest = hashlib.sha256(source.read_bytes() + PROFILE.encode()).hexdigest()[:12]
        with Image.open(source) as original:
            image = ImageOps.exif_transpose(original)
            image = image.convert("RGBA" if "A" in image.getbands() else "RGB")
            width, height = image.size
            widths = sorted({w for w in WIDTHS if w < width} | {min(width, 1600)})
            variants = []
            for target_width in widths:
                target_height = round(height * target_width / width)
                relative = f"homepage/optimized/{filename}-w{target_width}-{digest}.webp"
                output = STATIC / relative
                output.parent.mkdir(parents=True, exist_ok=True)
                if not output.exists():
                    resized = image.resize((target_width, target_height), Image.Resampling.LANCZOS)
                    resized.save(output, "WEBP", quality=90 if filename == "logo-transparent.png" else 80,
                                 method=6, exact=True, icc_profile=original.info.get("icc_profile", b""))
                variants.append({"path": relative, "width": target_width, "bytes": output.stat().st_size})
        images[filename] = {"width": width, "height": height, "src": variants[-1]["path"],
                            "variants": variants, "original_bytes": source.stat().st_size}
    target = ROOT / "templates/_homepage_image_data.html"
    target.write_text("{# Generated by scripts/optimize_homepage_images.py; do not edit by hand. #}\n"
                      + "{% set images = " + pprint.pformat(images, sort_dicts=True, width=120) + " %}\n", encoding="utf-8")
    print(json.dumps({"images": len(images), "variants": sum(len(v["variants"]) for v in images.values()),
                      "original_bytes": sum(v["original_bytes"] for v in images.values()),
                      "largest_variant_bytes": sum(v["variants"][-1]["bytes"] for v in images.values())}))


if __name__ == "__main__":
    main()
